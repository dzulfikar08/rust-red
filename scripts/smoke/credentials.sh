#!/usr/bin/env bash
# End-to-end smoke test for Node-RED's credentials file (flows_cred.json).
#
# The fixtures in crates/core/tests/fixtures/node_red_credentials were written by Node-RED 4.1.10
# (one with the key Node-RED generates, one with a credentialSecret). The flow is an inject that
# publishes to Mosquitto, an mqtt in that builds a row, and a node-red-contrib-postgresql insert.
# Mosquitto only accepts the user and password stored in flows_cred.json, PostgreSQL only the user
# and password stored there, so the row only arrives when the credentials were read.
#
# The flows are run as exported, apart from the ports of the two containers.
#
#   scripts/smoke/credentials.sh target/release/rust-red
#
# Needs docker, python3 and a built rust-red binary. Everything it starts is stopped again on exit.

set -euo pipefail

BIN=$(realpath "${1:?usage: credentials.sh <path to the rust-red binary>}")
ROOT=$(cd "$(dirname "$0")/../.." && pwd)
FIXTURES="$ROOT/crates/core/tests/fixtures/node_red_credentials"
WORK=$(mktemp -d)
PIDS=()
CONTAINERS=(rr-cred-pg rr-cred-mosq)
MQTT_PORT=11883
PG_PORT=15433
USER_SECRET='kéy secret ✓ for RustRED'

step() { printf '\n== %s\n' "$*"; }
fail() { printf 'FAIL: %s\n' "$*" >&2; exit 1; }

cleanup() {
    for pid in "${PIDS[@]:-}"; do [ -n "$pid" ] && kill "$pid" 2>/dev/null || true; done
    docker rm -f "${CONTAINERS[@]}" >/dev/null 2>&1 || true
    # mosquitto_passwd wrote the password file as root inside the container
    docker run --rm -v "$WORK:/w" busybox chmod -R a+rwX /w >/dev/null 2>&1 || true
    rm -rf "$WORK"
}
trap cleanup EXIT

psql_plant() { docker exec rr-cred-pg psql -U scada -d plant -tA -c "$1"; }

step "Mosquitto (user plant, password from flows_cred.json) and postgres:16-alpine (user scada)"
docker rm -f "${CONTAINERS[@]}" >/dev/null 2>&1 || true
mkdir -p "$WORK/mosq"
docker run --rm -v "$WORK/mosq:/m" eclipse-mosquitto:2 \
    mosquitto_passwd -b -c /m/passwd plant 'päss/wörd"1\x' >/dev/null
printf 'listener 1883\nallow_anonymous false\npassword_file /m/passwd\n' >"$WORK/mosq/mosquitto.conf"
docker run --rm -v "$WORK/mosq:/m" eclipse-mosquitto:2 chmod 644 /m/passwd
docker run -d --name rr-cred-mosq -p "127.0.0.1:$MQTT_PORT:1883" -v "$WORK/mosq:/m:ro" \
    eclipse-mosquitto:2 mosquitto -c /m/mosquitto.conf >/dev/null
docker run -d --name rr-cred-pg -e POSTGRES_USER=scada -e POSTGRES_PASSWORD=pg-secret-1 -e POSTGRES_DB=plant \
    -p "127.0.0.1:$PG_PORT:5432" postgres:16-alpine >/dev/null
for _ in $(seq 1 60); do docker exec rr-cred-pg pg_isready -U scada -d plant >/dev/null 2>&1 && break; sleep 1; done
sleep 3
psql_plant "CREATE TABLE smoke_log (id serial PRIMARY KEY, topic text, payload text)" >/dev/null

# name, extra rust-red arguments, environment
run_variant() {
    local name=$1; shift
    local dir="$WORK/$name"
    mkdir -p "$dir"
    cp "$FIXTURES/$name"/flows.json "$FIXTURES/$name"/flows_cred.json "$FIXTURES/$name"/.config.runtime.json "$dir/"
    python3 - "$dir/flows.json" "$MQTT_PORT" "$PG_PORT" <<'EOF'
import json, sys
path, mqtt_port, pg_port = sys.argv[1:]
flow = json.load(open(path))
for node in flow:
    if node["type"] == "mqtt-broker":
        node["port"] = mqtt_port
    if node["type"] == "postgreSQLConfig":
        node["port"] = pg_port
json.dump(flow, open(path, "w"))
EOF
    psql_plant "TRUNCATE smoke_log" >/dev/null
    (cd "$dir" && exec env "$@" "$BIN" run --headless --home "$WORK/home-$name" flows.json >"$dir/run.log" 2>&1) &
    PIDS+=($!)
    for _ in $(seq 1 30); do
        [ "$(psql_plant 'SELECT count(*) FROM smoke_log')" != 0 ] && break
        sleep 1
    done
    local rows
    rows=$(psql_plant "SELECT topic || '=' || payload FROM smoke_log")
    kill "${PIDS[-1]}" 2>/dev/null || true
    wait "${PIDS[-1]}" 2>/dev/null || true
    unset 'PIDS[-1]'
    [ "$rows" = "smoke/in=42" ] || { cat "$dir/run.log" >&2; fail "$name: expected the row smoke/in=42, got '$rows'"; }
    grep -q "Loaded credentials for 3 node" "$dir/run.log" || fail "$name: the credentials were not loaded"
    printf 'ok: %s\n' "$name"
}

step "Key generated by Node-RED (.config.runtime.json next to the flows)"
run_variant default-secret NODE_RED_CREDENTIAL_SECRET=

step "credentialSecret supplied through the environment"
run_variant user-secret "NODE_RED_CREDENTIAL_SECRET=$USER_SECRET"

step "Wrong secret stops the start with a clear error"
dir="$WORK/wrong"; mkdir -p "$dir"
cp "$FIXTURES/user-secret"/flows.json "$FIXTURES/user-secret"/flows_cred.json "$dir/"
if (cd "$dir" && NODE_RED_CREDENTIAL_SECRET=nope "$BIN" run --headless --home "$WORK/home-wrong" flows.json >"$dir/run.log" 2>&1); then
    fail "a wrong secret must not start"
fi
grep -q "credential secret is wrong" "$dir/run.log" || fail "no clear error for a wrong secret"
grep -q "nope" "$dir/run.log" && fail "the secret was logged"
printf 'ok: wrong secret\n'

printf '\nAll credentials smoke checks passed.\n'
